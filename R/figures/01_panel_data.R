#' Supplementary Table 2 with the values the code uses
#'
#' Parameter names, dimensions, definitions and sources are those of
#' `SUPP_TABLE2_TEXT`. Every value is read from `make_condition("S1")` and
#' `make_condition("S2")` (R/simulation/01_parameters.R) when the function is
#' called. A printed row that lists several parameters becomes one row per
#' parameter, so that each value is a number of its own; the remark in
#' brackets after the two recombination symbols is not repeated on their rows.
#' The two printed rows for the MIC of the compensated states each apply to
#' one scenario and have a value in that scenario's column only.
#'
#' @return A data frame of 82 rows in the printed order: `parameter`,
#'   `dimensions`, `definition`, `value_S1` and `value_S2` (the value in
#'   Scenario 1 and in Scenario 2, in the unit of `dimensions`; `NA` where the
#'   row does not apply to the scenario) and `source`.
supp_table2 <- function() {
  .need_simulation_modules(c("make_condition", "states"))
  p1  <- make_condition("S1")$p
  p2  <- make_condition("S2")$p
  non <- match(paste0("R", 0:9), states)
  cmp <- match(paste0("R", 0:9, "C"), states)
  # The minimum growth rate and the Hill coefficient are stored once per
  # state, with the same value for all 20.
  single <- function(x) {
    stopifnot(length(unique(x)) == 1)
    x[[1]]
  }
  # For each printed row, in order: how its values are read from a parameter
  # list p, and the scenarios it applies to.
  value_of <- list(
    function(p) p$v[non],
    function(p) p$v[cmp],
    function(p) c(p$mu, p$gamma),
    function(p) p$omega,
    function(p) single(p$vm),
    function(p) single(p$kH),
    function(p) p$M[non],
    function(p) p$M[cmp],
    function(p) p$M[cmp],
    function(p) p$P[non],
    function(p) p$P[cmp],
    function(p) p$KB,
    function(p) p$kmon,
    function(p) p$e,
    function(p) p$C,
    function(p) p$d,
    function(p) p$AMAX,
    function(p) p$dil
  )
  in_S1 <- !grepl(", Scenario 2$", SUPP_TABLE2_TEXT$definition)
  in_S2 <- !grepl(", Scenario 1$", SUPP_TABLE2_TEXT$definition)
  stopifnot(length(value_of) == nrow(SUPP_TABLE2_TEXT))

  rows <- lapply(seq_len(nrow(SUPP_TABLE2_TEXT)), function(i) {
    printed <- SUPP_TABLE2_TEXT[i, ]
    symbols <- strsplit(sub(" \\(.*\\)$", "", printed$parameter), ", ")[[1]]
    v1 <- value_of[[i]](p1)
    v2 <- value_of[[i]](p2)
    stopifnot(length(v1) == length(symbols), length(v2) == length(symbols))
    data.frame(parameter  = symbols,
               dimensions = printed$dimensions,
               definition = printed$definition,
               value_S1   = if (in_S1[i]) v1 else NA_real_,
               value_S2   = if (in_S2[i]) v2 else NA_real_,
               source     = printed$source,
               stringsAsFactors = FALSE)
  })
  out <- do.call(rbind, rows)
  rownames(out) <- NULL
  out
}

