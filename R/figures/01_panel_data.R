#' Tables of one tab of the source data workbook
#'
#' The plotted values are the panel's data frame with its values untouched.
#' Where the tab's column order differs from the frame's the columns are
#' reordered, the time column `t` is called `time`, and the rows of the
#' mean-density panels are sorted by time and then by state in the order of
#' `STATES`.
#'
#' Columns of `plotted`, by tab:
#'   Fig 1A, Fig 1B: `time`, the 20 state columns, `total`, `mean_copy`,
#'     `frac_compensated`.
#'   Fig 1C: `outcome`, `n`, `pct`, `ci_low`, `ci_high`.
#'   Fig 1D: `state`, `copy`, `compartment`, `mean_freq`, `sd_freq`.
#'   Fig 2A, Fig 2B, Fig 2C, Supp Fig 3: `time`, `state`, `copy`,
#'     `compartment`, `density`.
#'   Fig 2D, Fig 3B: `time`, `copy`, `freq`.
#'   Fig 3A: `time`, `scenario`, `mean_copy`.
#'   Fig 3C: `copy`, `scenario`, `net_growth`.
#'   Fig 4A, Fig 4B, Fig 4C: `outcome`, `parameter`, `label`, `median`, `max`.
#'   Supp Fig 4: `time`, the 20 state columns, `total`.
#'   Supp Fig 5A to 5F: `set`, the panel's parameter (`amax`, `omega`,
#'     `cost_per_copy`, `mu`, `dil`, `comp_frac` for A to F), `f_climb`,
#'     `f_lowcopy`, `f_extinct`.
#'   Supp Table 1: `state`, `dimensions`, `definition`.
#'   Supp Table 2: `parameter`, `dimensions`, `definition`, `value_S1`,
#'     `value_S2`, `source`.
#'
#' Columns of `per_replicate`, for the tabs that have one:
#'   Fig 1C: `seed`, `peak_mACN`, `final_N`, `outcome`.
#'   Fig 1D: `seed`, the 20 state columns (frequencies).
#'   Fig 2A, Fig 2B, Fig 2C, Supp Fig 3: `seed`, `time`, the 20 state columns
#'     (densities).
#'   Fig 3A: `seed`, `scenario`, `time`, `mean_copy`.
#'
#' Times are in hours and densities in cells per mL. Nothing is rounded.
#'
#' @param tab Character scalar, one of `SOURCE_DATA_TABS`.
#' @param pd Named list of the 17 panel data frames; by default the list this
#'   file has just computed, which is also the content of `PANEL_DATA_RDS`.
#' @return A list of two elements: `plotted`, a data frame, and
#'   `per_replicate`, a data frame or `NULL` for a tab without one.
source_data_tab <- function(tab, pd = panel_data) {
  if (length(tab) != 1 || !(tab %in% SOURCE_DATA_TABS))
    stop("Unknown tab. The tabs are: ",
         paste(SOURCE_DATA_TABS, collapse = ", "), call. = FALSE)

  plain <- function(d) {
    d <- as.data.frame(d)
    rownames(d) <- NULL
    d
  }
  with_time <- function(d, columns) {
    d <- plain(d)[, columns]
    names(d)[names(d) == "t"] <- "time"
    d
  }
  mean_densities <- function(d) {
    d <- as.data.frame(d)
    d <- d[order(d$t, match(d$state, STATES)), ]
    with_time(d, c("t", "state", "copy", "compartment", "density"))
  }
  sweep_parameter <- c("Supp Fig 5A" = "amax", "Supp Fig 5B" = "omega",
                       "Supp Fig 5C" = "cost_per_copy", "Supp Fig 5D" = "mu",
                       "Supp Fig 5E" = "dil", "Supp Fig 5F" = "comp_frac")

  plotted <- switch(tab,
    "Fig 1A" = plain(pd$Fig1A),
    "Fig 1B" = plain(pd$Fig1B),
    "Fig 1C" = plain(pd$Fig1C),
    "Fig 1D" = plain(pd$Fig1D),
    "Fig 2A" = mean_densities(pd$Fig2A),
    "Fig 2B" = mean_densities(pd$Fig2B),
    "Fig 2C" = mean_densities(pd$Fig2C),
    "Fig 2D" = with_time(pd$Fig2D, c("t", "copy", "freq")),
    "Fig 3A" = with_time(pd$Fig3A, c("t", "scenario", "mean_copy")),
    "Fig 3B" = with_time(pd$Fig3B, c("t", "copy", "freq")),
    "Fig 3C" = plain(pd$Fig3C),
    "Fig 4A" = plain(pd$Fig4A),
    "Fig 4B" = plain(pd$Fig4B),
    "Fig 4C" = plain(pd$Fig4C),
    "Supp Fig 3" = mean_densities(pd$FigS3),
    "Supp Fig 4" = plain(pd$FigS4),
    "Supp Table 1" = supp_table1(),
    "Supp Table 2" = supp_table2(),
    sweep_view(sweep_parameter[[tab]], pd)
  )

  per_replicate <- switch(tab,
    "Fig 1C" = replicate_outcomes(),
    "Fig 1D" = replicate_end_frequencies(),
    "Fig 2A" = replicate_states("S1", "S1_long", 72),
    "Fig 2B" = replicate_states("S1", "S1_long", 1000),
    "Fig 2C" = replicate_states("S1", "S1_long", 3000),
    "Fig 3A" = replicate_mean_copy(),
    "Supp Fig 3" = replicate_states("omega0", "omega0_long", 3000),
    NULL
  )

  list(plotted = plotted, per_replicate = per_replicate)
}

# Check of the long-run reduction ----

#' Derive the per-cycle reduction of the long run again and compare it
#'
#' Reads the raw hourly series with base R and repeats the reduction: the
#' suffix after the colon is removed from each column header, negative
#' densities are set to zero, the row with the largest time in each 24 h cycle
#' is kept, and the total of the 20 states is added. The result is compared
#' with the shipped per-cycle file value by value. The relative difference of
#' two values is their absolute difference divided by the larger of their
#' absolute values, and zero when both are zero.
#'
#' @param raw_csv Character scalar, path of the raw series.
#' @param percycle_csv Character scalar, path of the shipped reduction.
#' @param tol Numeric scalar, largest relative difference allowed.
#' @return The largest relative difference found, invisibly. Stops with an
#'   error if the two tables differ in shape or column names, or if any value
#'   differs by more than `tol`.
check_long_run_reduction <- function(raw_csv = LONG_RUN_CSV,
                                     percycle_csv = LONG_RUN_PERCYCLE,
                                     tol = 1e-12) {
  raw <- read.csv(raw_csv, check.names = FALSE, stringsAsFactors = FALSE)
  names(raw) <- gsub("^([A-Za-z0-9]+):.*$", "\\1", names(raw))
  raw[STATES] <- lapply(raw[STATES], function(x) { x[x < 0] <- 0; x })
  cycle <- floor(raw$TIME / 24)
  last  <- tapply(seq_len(nrow(raw)), cycle,
                  function(i) i[which.max(raw$TIME[i])])
  derived <- raw[last, c("TIME", STATES)]
  derived$total <- rowSums(derived[STATES])
  names(derived)[1] <- "time"

  shipped <- read.csv(percycle_csv, stringsAsFactors = FALSE)
  if (!identical(dim(derived), dim(shipped)) ||
      !identical(names(derived), names(shipped)))
    stop("The reduction derived from ", basename(raw_csv), " and ",
         basename(percycle_csv), " differ in shape or column names.",
         call. = FALSE)

  a <- as.matrix(derived)
  b <- as.matrix(shipped)
  largest <- pmax(abs(a), abs(b))
  rel     <- ifelse(largest > 0, abs(a - b) / largest, 0)
  worst   <- max(rel)
  if (!is.finite(worst) || worst > tol)
    stop("The reduction derived from ", basename(raw_csv), " differs from ",
         basename(percycle_csv), ": largest relative difference ",
         format(worst, digits = 3), ", allowed ", format(tol), ".",
         call. = FALSE)
  message("01_panel_data.R: long-run reduction confirmed, ", nrow(derived),
          " rows, largest relative difference ", format(worst, digits = 3))
  invisible(worst)
}
