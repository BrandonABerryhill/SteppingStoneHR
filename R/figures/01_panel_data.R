# The functions below add what the workbook shows beyond the 17 frames. They
# read the results again and leave the frames as they are.

# Stops with a message if objects of the simulation modules are not loaded.
.need_simulation_modules <- function(objects) {
  absent <- objects[!vapply(objects, exists, logical(1))]
  if (length(absent) > 0)
    stop("Not found: ", paste(absent, collapse = ", "),
         ". Source 00_config.R, 01_parameters.R and 04_classify.R of ",
         "R/simulation/ first.", call. = FALSE)
}

#' Outcome of every replicate behind Fig 1C
#'
#' Classifies the 4,000 compiled replicates of Scenario 1 on their transfer
#' rows with `classify_batch()` (R/simulation/04_classify.R). For the shipped
#' results the counts of these outcomes equal the stored counts that Fig 1C
#' shows.
#'
#' @return A data frame with one row per replicate, in seed order: `seed`,
#'   `peak_mACN` (peak mean copy number over the transfer rows), `final_N`
#'   (total density at 288 h, cells per mL) and `outcome` ("climb",
#'   "low-copy" or "extinction").
replicate_outcomes <- function() {
  .need_simulation_modules(c("classify_batch", "classify_outcome", "states",
                             "copy_number", "CLIMB_THRESHOLD", "EXTINCT_BELOW"))
  cls <- classify_batch(read_sims(HR_RESULTS, "S1", "S1_freq_cpp", "sims.rds"))
  out <- cls[, c("seed", "peak_mACN", "final_N", "outcome")]
  rownames(out) <- NULL
  out
}

#' State frequencies of every replicate behind Fig 1D
#'
#' @return A data frame with one row per replicate of the control batch, in
#'   seed order: `seed` and the 20 state columns, each the share of that state
#'   in the replicate's total density at 288 h. These are the rows of
#'   `.endfreq`, whose column means and standard deviations are `Fig1D`.
replicate_end_frequencies <- function() {
  out <- as.data.frame(.endfreq)
  names(out) <- STATES
  out <- cbind(seed = vapply(sofTr, function(df) df$seed[1], integer(1)), out)
  rownames(out) <- NULL
  out
}

#' State densities of every replicate behind a panel of mean densities
#'
#' Returns the rows that `ensemble_states()` and `states_long()` average for
#' the panel: every row of every replicate whose time, rounded to the hour, is
#' at most `tmax`. The mean shown at hour t is the mean of all rows whose time
#' rounds to t. In the 3,000 h batches a replicate has two such rows at each
#' transfer, the row of the 12 h grid and the transfer row.
#'
#' @param scenario Character scalar, scenario folder: "S1", "S2" or "omega0".
#' @param tag Character scalar, batch folder, for example "S1_long".
#' @param tmax Numeric scalar, end of the panel's window in hours.
#' @return A data frame sorted by seed and then by time: `seed`, `time` (h, as
#'   recorded) and the 20 state columns (cells per mL).
replicate_states <- function(scenario, tag, tmax) {
  sims <- read_sims(HR_RESULTS, scenario, tag, "sims.rds")
  out  <- do.call(rbind, lapply(sims, function(df) {
    df[round(df$time) <= tmax, c("seed", "time", STATES)]
  }))
  rownames(out) <- NULL
  out
}

#' Mean copy number of every replicate behind Fig 3A
#'
#' Applies `mc_from_states()` to each replicate of the two 3,000 h batches.
#' The line in Fig 3A is the mean copy number of the mean densities, so it is
#' not the average of this column.
#'
#' @return A data frame with one row per recorded row of each replicate,
#'   Scenario 1 first, sorted by seed and time within a scenario: `seed`,
#'   `scenario` ("Scenario 1" or "Scenario 2"), `time` (h, as recorded) and
#'   `mean_copy`.
replicate_mean_copy <- function() {
  one_batch <- function(scenario, tag, label) {
    sims <- read_sims(HR_RESULTS, scenario, tag, "sims.rds")
    do.call(rbind, lapply(sims, function(df) {
      data.frame(seed = df$seed, scenario = label, time = df$time,
                 mean_copy = mc_from_states(df), stringsAsFactors = FALSE)
    }))
  }
  out <- rbind(one_batch("S1", "S1_long", "Scenario 1"),
               one_batch("S2", "S2_long", "Scenario 2"))
  rownames(out) <- NULL
  out
}

