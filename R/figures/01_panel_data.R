#' PAWN indices of one outcome, in plotting order
#'
#' @param tab One element of the stored PAWN list: a table with one row per
#'   parameter, named by its row names, and the columns `median` and `max`.
#' @param outcome Character scalar, label of the outcome.
#' @return A data frame of six rows in the order of `param_order`: `outcome`,
#'   `parameter`, `label`, `median` and `max`. The last two are the median
#'   and the maximum of the Kolmogorov-Smirnov distance over the quantile bins
#'   of the parameter, as stored; the median is the index the paper reports.
pawn_df <- function(tab, outcome) {
  tab <- as.data.frame(tab); tab$parameter <- rownames(tab)
  tab <- tab[match(param_order, tab$parameter), ]
  data.frame(outcome   = outcome,
             parameter = tab$parameter,
             label     = unname(param_labels[tab$parameter]),
             median    = tab$median,
             max       = tab$max,
             row.names = NULL, stringsAsFactors = FALSE)
}
