# 01_panel_data.R
#
# The data behind every figure panel and every tab of the source data
# workbook. Sourcing this file reads the shipped results, computes one data
# frame per figure panel, 17 in all (Supplementary Fig 5 has a single frame
# for its six panels), and writes them to source_data/panel_data.rds as
# list(data = <named list of the 17 frames>). The figure scripts read that
# file, and the tables of the workbook are taken from the same frames, so a
# panel and its tab cannot disagree.
#
# Inputs. The working directory must be the repository root: 00_style.R,
# which this file sources if it has not been sourced yet, records it as PROJ
# and every path is built from it. Results are read from HR_RESULTS, by
# default PROJ/results; a script that assigns HR_RESULTS before sourcing this
# file keeps its own folder. Batches are read from
# HR_RESULTS/<scenario>/<tag>/sims.rds, the stored outcome frequencies from
# HR_RESULTS/frequency_summary.rds, and the sweep and PAWN tables from the
# folder under HR_RESULTS/sensitivity/ that holds both sweep.csv and pawn.rds;
# if there are several, the last in alphabetical order is taken. The shipped
# results hold one, sweep_S1. The series behind Supplementary Fig 4 is read
# from PROJ/results/long_run/. It comes from an old iteration of the model and
# is not regenerated by this code.
#
# Source data workbook. SOURCE_DATA_TABS names the 24 data tabs in manuscript
# order, and source_data_tab(tab) returns the tables of one tab as
# list(plotted = <data frame>, per_replicate = <data frame or NULL>), with
# plain column names in the order the tab shows them. A per-replicate table
# is read from the batch behind the panel and holds the rows that the panel's
# mean or frequency summarises. Supplementary Tables 1 and 2 and the
# per-replicate table of Fig 1C use the states vector, make_condition() and
# classify_batch(), so 00_config.R, 01_parameters.R and 04_classify.R of
# R/simulation/ have to be sourced before those tabs are requested. Sourcing
# this file does not need them.
#
# check_long_run_reduction() derives the per-cycle reduction of the long run
# again from the raw file and compares it with the shipped reduction. It reads
# a 65 MB file, so it runs only when it is called.
#
# Part of the code for "Unstable Heteroresistance as a Stepping Stone to Stable
# Resistance via Compensatory Mutations" (Berryhill and Andersson).
#
# Defines: HR_RESULTS, LONG_RUN_PERCYCLE, LONG_RUN_CSV, SENS_DIR, read_sims(),
# ensemble_states(), mc_from_states(), traj_df(), states_long(),
# comp_freq_long(), net_growth_by_copy(), pawn_df(), the objects read from
# the results (trS1, sofTr, emS1, emS2, emSof, freqS, pawn, sweep), the 17
# panel data frames (Fig1A to Fig1D, Fig2A to Fig2D, Fig3A to Fig3C, Fig4A to
# Fig4C, FigS3, FigS4, FigS5) with the objects they are built from (.endfreq,
# M_R, param_order, param_labels), .fig3C_S1_check and the list panel_data
# that holds the 17 frames; for the workbook, .need_simulation_modules(),
# SOURCE_DATA_TABS, source_data_tab(), replicate_outcomes(),
# replicate_end_frequencies(), replicate_states(), replicate_mean_copy(),
# sweep_view(), SUPP_TABLE1_TEXT, SUPP_TABLE2_TEXT, supp_table1() and
