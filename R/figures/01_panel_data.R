#' The sweep table as one panel of Supplementary Fig 5 shows it
#'
#' @param parameter Character scalar, the parameter on the panel's x axis: one
#'   of "amax", "omega", "cost_per_copy", "mu", "dil" or "comp_frac".
#' @param pd Named list of the panel data frames.
#' @return A data frame of one row per parameter set: `set` (the set's number,
#'   which is its row in the sweep table), the column named by `parameter`,
#'   and `f_climb`, `f_lowcopy` and `f_extinct` (fraction of the set's
#'   replicates with each outcome).
sweep_view <- function(parameter, pd = panel_data) {
  d <- pd$FigS5
  data.frame(set = seq_len(nrow(d)), d[parameter],
             d[c("f_climb", "f_lowcopy", "f_extinct")])
}

