# STATES, COPY and state_info come from 00_style.R.

# A batch file holds a list of data frames, one per replicate, named by seed.
read_sims <- function(...) readRDS(file.path(...))

#' Mean density of each state across the replicates of a batch
#'
#' Times are rounded to the hour and the mean is taken over every row of every
#' replicate that shares a rounded time. The 3,000 h batches are recorded
#' every 12 h and at every transfer, so at each transfer a replicate has two
#' rows one time step apart; both fall on the same hour and both enter the
#' mean.
#'
#' @param sims List of data frames, one per replicate, each with `time` (h)
#'   and the 20 state columns (cells per mL).
#' @return A tibble with one row per rounded time: `t` (h) and the 20 state
#'   columns, each the mean density in cells per mL.
ensemble_states <- function(sims) {
  big <- bind_rows(sims, .id = "seed")
  big$t <- round(big$time)
  big |>
    group_by(t) |>
    summarise(across(all_of(STATES), mean), .groups = "drop")
}

#' Mean copy number of each row of a table of state densities
#'
#' @param em Data frame with the 20 state columns (cells per mL).
#' @return Numeric vector, one value per row: the sum of copy number times
#'   density divided by the total density, `NA` where the total is not
#'   positive.
mc_from_states <- function(em) {
  M <- as.matrix(em[STATES]); tot <- rowSums(M); tot[tot <= 0] <- NA_real_
  as.numeric(M %*% COPY) / tot
}

#' Trajectory of one replicate
#'
#' @param df Data frame of one replicate, with `time` (h) and the 20 state
#'   columns (cells per mL).
#' @return A data frame with one row per row of `df`: `time`, the 20 state
#'   columns, `total` (total density, cells per mL), `mean_copy` (mean copy
#'   number) and `frac_compensated` (compensated fraction of the total
#'   density). The last two are `NA` where the total is not positive.
traj_df <- function(df) {
  d <- df[, c("time", STATES)]
  M <- as.matrix(d[STATES]); tot <- rowSums(M); tot[tot <= 0] <- NA_real_
  d$total            <- rowSums(M)
  d$mean_copy        <- as.numeric(M %*% COPY) / tot
  d$frac_compensated <- rowSums(d[paste0("R", 0:9, "C")]) / tot
  d
}

#' Mean densities in long form, up to a given time
#'
#' @param em Tibble returned by `ensemble_states()`.
#' @param tmax Numeric scalar, last time kept, in hours.
#' @return A tibble with one row per time and state: `t` (h), `state`,
#'   `density` (cells per mL), `copy` and `compartment`, sorted by time, copy
#'   number and compartment.
states_long <- function(em, tmax) {
  em[em$t <= tmax, ] |>
    pivot_longer(all_of(STATES), names_to = "state", values_to = "density") |>
    left_join(state_info, by = "state") |>
    arrange(t, copy, compartment)
}

#' Share of each compensated state in the total population, over time
#'
#' The denominator is the total density of all 20 states, so the ten values
#' at one time add up to the compensated fraction of the population, not to
#' one.
#'
#' @param em Tibble returned by `ensemble_states()`.
#' @return A tibble with one row per time and copy number: `t` (h), `copy`
#'   (0 to 9) and `freq`, the mean density of the compensated state with that
#'   copy number divided by the total mean density; `NA` where the total is
#'   zero.
comp_freq_long <- function(em) {
  M   <- as.matrix(em[STATES]); tot <- rowSums(M)
  cmp <- as.matrix(em[paste0("R", 0:9, "C")]) / ifelse(tot > 0, tot, NA_real_)
  colnames(cmp) <- as.character(0:9)
  d <- as.data.frame(cmp); d$t <- em$t
  pivot_longer(d, as.character(0:9), names_to = "copy", values_to = "freq") |>
    mutate(copy = as.integer(copy)) |>
    arrange(t, copy)
}

#' Net growth rate of the ten compensated states at a given antibiotic
#' concentration
#'
#' The expression is the net growth rate of Supplementary Equation 1 as the R
#' reference engine computes it (R/simulation/03_engine_R.R), without the
#' resource term of Supplementary Equation 2, so it is the rate at unlimited
#' resource. The defaults are the values `make_condition()` sets
#' (R/simulation/01_parameters.R).
#'
#' @param A Numeric scalar, antibiotic concentration in micrograms per mL.
#' @param M_C Numeric vector of length 10, MIC of the compensated states with
#'   0 to 9 copies, in micrograms per mL.
#' @param cost Numeric scalar, per-copy cost on the maximum growth rate, per
#'   cell per hour.
#' @param comp_frac Numeric scalar, fraction of the cost that compensation
#'   recovers.
#' @param vmax Numeric scalar, maximum growth rate at zero copies, per cell
#'   per hour.
#' @param vm Numeric scalar, minimum growth rate, per cell per hour.
#' @param kH Numeric scalar, Hill coefficient.
#' @return Numeric vector of length 10, net growth rate per cell per hour for
#'   copy numbers 0 to 9.
net_growth_by_copy <- function(A, M_C, cost = 0.0013, comp_frac = 0.5,
                               vmax = 2, vm = -2, kH = 1) {
  copy <- 0:9
  vC   <- vmax - (1 - comp_frac) * cost * copy
  AM   <- (A / M_C)^kH
  HH   <- ((vC - vm) * AM) / (AM - vm / vC)
  vC - HH
}

